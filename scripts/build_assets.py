def highlight(x: float, y: float, w: float, h: float, i: int) -> str:
    return (f'<rect class="hl" style="animation-delay:{i * 1.2:.1f}s" x="{x:.1f}" y="{y}" width="{w:.1f}" '
            f'height="{h}" rx="10" fill="none" stroke="{ACCENT}" stroke-width="1.5" opacity="0"/>')


