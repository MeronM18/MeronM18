def tool_line(items: list[str], x: float, y: float, size: float, lead: bool) -> tuple[list[str], float]:
    out = []
    for j, item in enumerate(items):
        if j:
            out.append(text(SEP, x, y, size, DIM))
            x += text_width(SEP, size)
        out.append(text(item, x, y, size, TEXT if lead and j == 0 else SOFT))
        x += text_width(item, size)
    return out, x


