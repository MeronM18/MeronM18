_fonts: dict[str, TTFont] = {}


def font(weight: str) -> TTFont:
    if weight not in _fonts:
        path = FONT_DIR / f"IBMPlexMono-{weight}.ttf"
        if not path.exists():
            FONT_DIR.mkdir(exist_ok=True)
            urllib.request.urlretrieve(FONT_URL.format(weight), path)
        _fonts[weight] = TTFont(path)
    return _fonts[weight]


def text_width(s: str, size: float, weight: str = "Regular", spacing: float = 0) -> float:
    f = font(weight)
    cmap = f.getBestCmap()
    total = sum(f["hmtx"][cmap[ord(ch)]][0] for ch in s) * size / f["head"].unitsPerEm
    return total + spacing * (len(s) - 1)


def text(s: str, x: float, y: float, size: float, fill: str, weight: str = "Regular",
         spacing: float = 0, anchor: str = "start") -> str:
    """Outline `s` as a single <path>, with (x, y) at the baseline."""
    f = font(weight)
    cmap = f.getBestCmap()
    glyphs = f.getGlyphSet()
    scale = size / f["head"].unitsPerEm
    if anchor == "end":
        x -= text_width(s, size, weight, spacing)
    elif anchor == "middle":
        x -= text_width(s, size, weight, spacing) / 2
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    cursor = x
    for ch in s:
        if ord(ch) not in cmap:
            raise ValueError(f"IBM Plex Mono has no glyph for {ch!r}")
        name = cmap[ord(ch)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cursor, y)))
        cursor += f["hmtx"][name][0] * scale + spacing
    return f'<path fill="{fill}" d="{pen.getCommands()}"/>'


def wrap(words: list[str], size: float, width: float, sep: str) -> list[list[str]]:
    """Greedy line-wrap of `words` joined by `sep` into lines no wider than `width`."""
    lines: list[list[str]] = [[]]
    for w in words:
        trial = sep.join(lines[-1] + [w])
        if lines[-1] and text_width(trial, size) > width:
            lines.append([w])
        else:
            lines[-1].append(w)
    return lines


def svg(width: float, height: float, title: str, desc: str, body: list[str], animated: bool = False) -> str:
    style = f"\n  <style>{MOTION_CSS}</style>" if animated else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title description">\n'
        f'  <title id="title">{title}</title>\n'
        f'  <desc id="description">{desc}</desc>\n'
        f"  <!-- Generated by scripts/build_assets.py. Text is outlined from IBM Plex Mono (SIL OFL 1.1). -->"
        f"{style}\n  " + "\n  ".join(body) + "\n</svg>\n"
    )


def window(width: float, height: float, caption: str, cursor: bool = False) -> list[str]:
    """Dark terminal window chrome, matching the header."""
    cap = 12 if width == DESKTOP else 13
    parts = [
        f'<rect width="{width}" height="{height}" rx="18" fill="{BG}"/>',
        f'<rect x="0.75" y="0.75" width="{width - 1.5}" height="{height - 1.5}" rx="17.25" '
        f'fill="none" stroke="{BORDER}" stroke-width="1.5"/>',
        f'<circle cx="30" cy="28" r="4" fill="{ACCENT}" opacity="0.9"/>'
        f'<circle cx="46" cy="28" r="4" fill="{DIM}"/><circle cx="62" cy="28" r="4" fill="{DIMMER}"/>',
        text(caption, 86.5, 33, cap, MUTED),
        f'<line x1="24" y1="52" x2="{width - 24}" y2="52" stroke="{RULE}"/>',
    ]
    if cursor:
        cx = 86.5 + text_width(caption, cap) + 5
        parts.append(f'<rect class="cursor" x="{cx:.1f}" y="23.5" width="7" height="12" fill="{ACCENT}"/>')
    return parts


def status_dot(cx: float, cy: float, color: str, pulse: bool) -> list[str]:
    out = [f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="4" fill="{color}"/>']
    if pulse:
        out.append(f'<circle class="ring" cx="{cx:.1f}" cy="{cy:.1f}" r="4" fill="none" '
                   f'stroke="{color}" stroke-width="1.5" opacity="0"/>')
    return out


def write(name: str, content: str) -> None:
    (ASSETS / name).write_text(content)
    print(f"wrote assets/{name} ({len(content) / 1024:.1f} KB)")


